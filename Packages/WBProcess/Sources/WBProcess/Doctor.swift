import Foundation
import WBCore

public enum CheckStatus: String, Codable, Sendable, Equatable {
  case pass
  case warn
  case fail
}

public struct EnvironmentCheck: Codable, Sendable, Equatable {
  public var name: String
  public var status: CheckStatus
  public var summary: String
  public var fix: String?

  public init(name: String, status: CheckStatus, summary: String, fix: String? = nil) {
    self.name = name
    self.status = status
    self.summary = summary
    self.fix = fix
  }
}

public struct DoctorReport: Codable, Sendable, Equatable {
  public var checks: [EnvironmentCheck]
  public var pathPrefixes: [String]
  public var sdkRoot: String?

  public init(checks: [EnvironmentCheck], pathPrefixes: [String], sdkRoot: String?) {
    self.checks = checks
    self.pathPrefixes = pathPrefixes
    self.sdkRoot = sdkRoot
  }

  public var hasFailures: Bool {
    checks.contains { $0.status == .fail }
  }
}

public struct Doctor: Sendable {
  public var path: String
  public var home: URL
  public var osMajor: Int
  public var architecture: String
  public var environment: [String: String]
  public var locator: any ToolLocating
  public var runner: any CommandExecuting

  public init(
    path: String,
    home: URL,
    osMajor: Int,
    architecture: String,
    environment: [String: String],
    locator: any ToolLocating,
    runner: any CommandExecuting
  ) {
    self.path = path
    self.home = home
    self.osMajor = osMajor
    self.architecture = architecture
    self.environment = environment
    self.locator = locator
    self.runner = runner
  }

  public static func live() -> Doctor {
    let version = ProcessInfo.processInfo.operatingSystemVersion
    let environment = ProcessInfo.processInfo.environment
    return Doctor(
      path: environment["PATH"] ?? "",
      home: FileManager.default.homeDirectoryForCurrentUser,
      osMajor: version.majorVersion,
      architecture: MachineArchitecture.current(),
      environment: environment,
      locator: SystemToolLocator(),
      runner: SystemCommandRunner()
    )
  }

  public func inspect() async -> DoctorReport {
    var checks: [EnvironmentCheck] = []
    var prefixes: [String] = []

    if osMajor >= 15 {
      checks.append(
        EnvironmentCheck(name: "macOS", status: .pass, summary: "macOS \(osMajor).")
      )
    } else {
      checks.append(
        EnvironmentCheck(
          name: "macOS",
          status: .fail,
          summary: "macOS \(osMajor) is older than 15.",
          fix: "Install macOS 15 or newer."
        )
      )
    }

    if architecture == "arm64" {
      checks.append(
        EnvironmentCheck(name: "CPU", status: .pass, summary: "Apple Silicon (arm64).")
      )
    } else {
      checks.append(
        EnvironmentCheck(
          name: "CPU",
          status: .warn,
          summary: "This Mac reports \(architecture). QA Workbench is tested on Apple Silicon.",
          fix: "Use an Apple Silicon Mac."
        )
      )
    }

    checks.append(await xcodeCheck())
    let swiftTool = await tool(
      name: "swift",
      versionArguments: ["--version"],
      install: "Install Xcode 16 or newer."
    )
    let flutterTool = await tool(
      name: "flutter",
      versionArguments: ["--version"],
      install: "Install Flutter and put ~/develop/flutter/bin on PATH."
    )
    let adbTool = await tool(
      name: "adb",
      versionArguments: ["version"],
      install: "Install Android Studio or the SDK command-line tools."
    )
    let emulatorTool = await tool(
      name: "emulator",
      versionArguments: ["-version"],
      install: "Install the Android emulator package in the SDK."
    )
    for item in [swiftTool, flutterTool, adbTool, emulatorTool] {
      checks.append(item.0)
      if let prefix = item.1 {
        prefixes.append(prefix)
      }
    }

    let sdk = resolveSDK()
    checks.append(sdkCheck(sdk))
    if let emulator = find("emulator"), sdk?.url != nil {
      checks.append(await avdCheck(emulator: emulator.url))
    }
    checks.append(await simctlCheck())
    checks.append(optionalTool(name: "idb", missing: idbWarning))
    checks.append(optionalTool(name: "mitmdump", missing: mitmWarning))

    return DoctorReport(
      checks: checks,
      pathPrefixes: prefixes,
      sdkRoot: sdk?.url.path
    )
  }

  public static func writeFix(_ report: DoctorReport, to directory: URL) throws -> URL? {
    var lines = [
      "# Generated by QA Workbench. Your shell does not load this file until you source it."
    ]
    let sdkWarned = report.checks.contains { $0.name == "Android SDK" && $0.status == .warn }
    if sdkWarned, let sdk = report.sdkRoot {
      lines.append("export ANDROID_SDK_ROOT=\"\(sdk)\"")
      lines.append("export ANDROID_HOME=\"$ANDROID_SDK_ROOT\"")
    }
    if !report.pathPrefixes.isEmpty {
      lines.append("export PATH=\"\(report.pathPrefixes.joined(separator: ":")):$PATH\"")
    }
    guard lines.count > 1 else { return nil }
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    let url = directory.appendingPathComponent("env.sh")
    try (lines.joined(separator: "\n") + "\n").write(to: url, atomically: true, encoding: .utf8)
    return url
  }

  private func xcodeCheck() async -> EnvironmentCheck {
    let install = "Install Xcode 16 or newer."
    guard let hit = find("xcodebuild") else {
      return EnvironmentCheck(
        name: "Xcode", status: .fail, summary: "xcodebuild was not found.", fix: install)
    }
    let result: CommandResult
    do {
      result = try await runner.execute(
        executable: hit.url,
        arguments: ["-version"],
        timeout: .seconds(30),
        environment: nil
      )
    } catch {
      return EnvironmentCheck(
        name: "Xcode", status: .fail, summary: "xcodebuild did not finish.", fix: install)
    }
    let summary =
      firstLine(result.stdoutText).isEmpty
      ? firstLine(result.stderrText) : firstLine(result.stdoutText)
    guard result.status == 0 else {
      return EnvironmentCheck(name: "Xcode", status: .fail, summary: summary, fix: install)
    }
    if let major = firstNumber(in: summary), major < 16 {
      return EnvironmentCheck(
        name: "Xcode",
        status: .fail,
        summary: "\(summary) is older than Xcode 16.",
        fix: install
      )
    }
    return EnvironmentCheck(name: "Xcode", status: .pass, summary: summary)
  }

  private func tool(
    name: String,
    versionArguments: [String],
    install: String
  ) async -> (EnvironmentCheck, String?) {
    guard let hit = find(name) else {
      return (
        EnvironmentCheck(
          name: name, status: .fail, summary: "\(name) was not found.", fix: install),
        nil
      )
    }
    let result: CommandResult
    do {
      result = try await runner.execute(
        executable: hit.url,
        arguments: versionArguments,
        timeout: .seconds(30),
        environment: nil
      )
    } catch {
      return (
        EnvironmentCheck(
          name: name, status: .fail, summary: "Could not run \(name).", fix: install),
        nil
      )
    }
    let line =
      firstLine(result.stdoutText).isEmpty
      ? firstLine(result.stderrText) : firstLine(result.stdoutText)
    guard result.status == 0 else {
      return (
        EnvironmentCheck(
          name: name, status: .fail, summary: "\(name) failed: \(line)", fix: install),
        nil
      )
    }
    if hit.onPath {
      return (EnvironmentCheck(name: name, status: .pass, summary: line), nil)
    }
    let directory = hit.url.deletingLastPathComponent().path
    return (
      EnvironmentCheck(
        name: name,
        status: .warn,
        summary: "\(line) Found at \(hit.url.path), which is not on PATH.",
        fix: "export PATH=\"\(directory):$PATH\""
      ),
      directory
    )
  }

  private func sdkCheck(_ sdk: (url: URL, fromEnvironment: Bool)?) -> EnvironmentCheck {
    guard let sdk else {
      return EnvironmentCheck(
        name: "Android SDK",
        status: .fail,
        summary: "No Android SDK was found.",
        fix: "Install the SDK and set ANDROID_SDK_ROOT."
      )
    }
    if sdk.fromEnvironment {
      return EnvironmentCheck(
        name: "Android SDK",
        status: .pass,
        summary: sdk.url.path
      )
    }
    return EnvironmentCheck(
      name: "Android SDK",
      status: .warn,
      summary: "SDK is at \(sdk.url.path), and ANDROID_SDK_ROOT is unset.",
      fix: "export ANDROID_SDK_ROOT=\"\(sdk.url.path)\""
    )
  }

  private func avdCheck(emulator: URL) async -> EnvironmentCheck {
    let result: CommandResult
    do {
      result = try await runner.execute(
        executable: emulator,
        arguments: ["-list-avds"],
        timeout: .seconds(30),
        environment: nil
      )
    } catch {
      return EnvironmentCheck(
        name: "AVDs",
        status: .warn,
        summary: "Could not list AVDs.",
        fix: "Run emulator -list-avds in Terminal."
      )
    }
    let names = result.stdoutText.split(whereSeparator: \.isNewline).map(String.init).filter {
      !$0.isEmpty
    }
    if names.isEmpty {
      return EnvironmentCheck(
        name: "AVDs",
        status: .warn,
        summary: "The emulator has no AVDs.",
        fix: "Create an AVD in Android Studio."
      )
    }
    return EnvironmentCheck(name: "AVDs", status: .pass, summary: names.joined(separator: ", "))
  }

  private func simctlCheck() async -> EnvironmentCheck {
    let install = "Install Xcode 16 or newer. simctl ships with it."
    guard let xcrun = find("xcrun") else {
      return EnvironmentCheck(
        name: "simctl", status: .fail, summary: "xcrun was not found.", fix: install)
    }
    let result: CommandResult
    do {
      result = try await runner.execute(
        executable: xcrun.url,
        arguments: ["simctl", "list", "runtimes", "-j"],
        timeout: .seconds(40),
        environment: nil
      )
    } catch {
      return EnvironmentCheck(
        name: "simctl", status: .fail, summary: "simctl did not finish.", fix: install)
    }
    guard result.status == 0 else {
      return EnvironmentCheck(
        name: "simctl",
        status: .fail,
        summary: firstLine(result.stderrText),
        fix: install
      )
    }
    guard let data = result.stdoutText.data(using: .utf8),
      let parsed = try? JSONDecoder().decode(RuntimeList.self, from: data)
    else {
      return EnvironmentCheck(
        name: "iOS runtimes",
        status: .fail,
        summary: "simctl returned a runtime list that could not be read.",
        fix: install
      )
    }
    let available = parsed.runtimes.filter { runtime in
      let name = runtime.name ?? ""
      return name.contains("iOS") && runtime.isAvailable != false
    }
    if available.isEmpty {
      return EnvironmentCheck(
        name: "iOS runtimes",
        status: .fail,
        summary: "No available iOS simulator runtime is installed.",
        fix: "Install an iOS simulator runtime from Xcode."
      )
    }
    let names = available.compactMap(\.name).joined(separator: ", ")
    return EnvironmentCheck(name: "iOS runtimes", status: .pass, summary: names)
  }

  private func optionalTool(name: String, missing: EnvironmentCheck) -> EnvironmentCheck {
    guard find(name) != nil else { return missing }
    return EnvironmentCheck(name: name, status: .pass, summary: "\(name) is installed.")
  }

  private func find(_ name: String) -> ToolHit? {
    locator.find(
      named: name,
      path: path,
      extraDirectories: KnownTools.extraDirectories(for: name, home: home)
    )
  }

  private func resolveSDK() -> (url: URL, fromEnvironment: Bool)? {
    for key in ["ANDROID_SDK_ROOT", "ANDROID_HOME"] {
      if let raw = environment[key], !raw.isEmpty {
        let url = URL(fileURLWithPath: raw)
        if directoryExists(url) {
          return (url, true)
        }
      }
    }
    let fallback = home.appendingPathComponent("Library/Android/sdk")
    if directoryExists(fallback) {
      return (fallback, false)
    }
    return nil
  }

  private func directoryExists(_ url: URL) -> Bool {
    var isDirectory: ObjCBool = false
    return FileManager.default.fileExists(atPath: url.path, isDirectory: &isDirectory)
      && isDirectory.boolValue
  }

  private func firstLine(_ text: String) -> String {
    text.split(whereSeparator: \.isNewline).first.map(String.init) ?? ""
  }

  private func firstNumber(in text: String) -> Int? {
    let digits = text.split(whereSeparator: { !$0.isNumber })
    return digits.first.flatMap { Int($0) }
  }

  private var idbWarning: EnvironmentCheck {
    EnvironmentCheck(
      name: "idb",
      status: .warn,
      summary: "idb is not installed. iOS input stays on the simctl fallback.",
      fix: "Homebrew has no idb formula. iOS taps are not available in this version."
    )
  }

  private var mitmWarning: EnvironmentCheck {
    EnvironmentCheck(
      name: "mitmdump",
      status: .warn,
      summary: "mitmdump is not installed. Installed-app HTTP capture needs it.",
      fix:
        "python3 -m venv \"$HOME/Library/Application Support/QA Workbench/mitmvenv\" && \"$HOME/Library/Application Support/QA Workbench/mitmvenv/bin/pip\" install mitmproxy"
    )
  }
}

private struct RuntimeList: Decodable {
  var runtimes: [RuntimeEntry]
}

private struct RuntimeEntry: Decodable {
  var name: String?
  var isAvailable: Bool?
}
